"""Generate the C++ pins from specs.json: the record sizes (src/Empire Earth/Database/EEDataTextSpecs.h) and the dbworld
constants (rust/crates/ee_data/src/world_constants.rs, a Rust enum cbindgen emits back as the C++ EEWorldConstant:
include/rust/data/world_constants.h through ee/EEWorldConstants.h). The text compiler's specs are Rust (rustgen.py).

  python -I tools/eedata/eedata.py cppgen [--check]
"""
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
OUT = ROOT / 'src' / 'Empire Earth' / 'Database' / 'EEDataTextSpecs.h'
WORLD_OUT = ROOT / 'rust' / 'crates' / 'ee_data' / 'src' / 'world_constants.rs'
# the records whose C++ structs EEDataTextFile.cpp pins (the others are Rust records or read through ee_data)
PINS = ('EEWorldTableEntry', 'EECPBehavior', 'EETechTreeRecord', 'EEUnitClassRecord')


def generate(spec):
    """EEDataTextSpecs.h: the record sizes, for EEDataTextFile.cpp's static_asserts against the structs the loaders
    read (the text compiler's own specs are Rust: rustgen.py)."""
    o = ['// GENERATED by tools/eedata/cppgen.py from tools/eedata/specs.json: do not edit (eedata.py cppgen).',
         '// The db record sizes the C++ pins: the text compiler itself is Rust (tools/eedata/rustgen.py).',
         '#ifndef EE_DATATEXTSPECS_H',
         '#define EE_DATATEXTSPECS_H',
         '',
         '// record sizes (EEDataTextFile.cpp static_asserts them against the structs the loaders read)',
         'enum EEDTRecordSize {']
    for sname in PINS:
        o.append(f'    kEEDTSize_{sname} = {spec["structs"][sname]["size"]},')
    o += ['};', '', '#endif']
    return ('\n'.join(o) + '\n').encode('ascii')


def camel(snake):
    return ''.join(w[:1].upper() + w[1:] for w in snake.split('_'))


VALUE_NAMES = {'mFloatValue': 'F', 'mFloatValue2': 'F2', 'mLongValue': 'L', 'mLongValue2': 'L2'}


def generate_world(spec):
    """rust/crates/ee_data/src/world_constants.rs: dbworld's rows by their ids (the constants' names) as a Rust enum
    that cbindgen emits back as the C++ enum EEWorldConstant (include/rust/data/world_constants.h, which
    ee/EEWorldConstants.h includes): the code reads a constant as gWorldTable.GetLongValue(kWorldUnitLimitRange),
    never by a raw row number."""
    names = spec['row_names']['dbworld']
    fields = spec['tables']['dbworld'].get('row_fields', {})
    o = ['// GENERATED by tools/eedata/cppgen.py from tools/eedata/specs.json (overlay.WORLD_ROWS): do not edit',
         '// (eedata.py cppgen).',
         '//! The dbworld constants by their ids, as a plain (unscoped) C enum for the C++ headers (ee/EEWorldConstants.h).',
         '#![allow(non_camel_case_types, non_upper_case_globals, clippy::enum_variant_names)]',
         '',
         '/// The dbworld constants by their ids: the row of each (its runtime key) and the values its readers use (F',
         '/// mFloatValue, F2 mFloatValue2, L mLongValue, L2 mLongValue2; docs/DATA_FORMATS.md 8.3). The EEWorldTable',
         '/// accessors take an EEWorldConstant, so a raw row number does not compile.',
         '/// cbindgen:enum-class=false',
         '#[repr(C)]',
         '#[derive(Clone, Copy, Debug, PartialEq, Eq)]',
         'pub enum EEWorldConstant {']
    rows = sorted(names.items(), key=lambda kv: int(kv[0]))
    for k, v in rows:
        used = ' '.join(VALUE_NAMES[f] for f in fields.get(k, []))
        o.append(f'    /// {v}: {used}'.rstrip())
        o.append(f'    kWorld{camel(v)} = {int(k)},')
    o.append('}')
    o.append('')
    o.append('#[cfg(test)]')
    o.append('mod tests {')
    o.append('    use super::*;')
    o.append('')
    o.append('    /// The first and the last row keep their dbworld ids.')
    o.append('    #[test]')
    o.append('    fn rows() {')
    for k, v in (rows[0], rows[-1]):
        o.append(f'        assert_eq!(EEWorldConstant::kWorld{camel(v)} as i32, {int(k)});')
    o.append('    }')
    o.append('}')
    return ('\n'.join(o) + '\n').encode('ascii')


def run(a, spec):
    status = 0
    for out, new in ((OUT, generate(spec)), (WORLD_OUT, generate_world(spec))):
        if a.check:
            ok = out.exists() and out.read_bytes() == new
            print(f'{out.name} is ' + ('up to date' if ok else 'STALE: run eedata.py cppgen'))
            status |= 0 if ok else 1
            continue
        out.write_bytes(new)
        print(f'-> {out}')
    return status
