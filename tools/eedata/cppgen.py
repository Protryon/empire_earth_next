"""Generate the C++ pins from specs.json: the record sizes (src/Empire Earth/Database/EEDataTextSpecs.h) and the dbworld
constants (include/ee/EEWorldConstants.h). The text compiler's specs are Rust (rustgen.py).

  python -I tools/eedata/eedata.py cppgen [--check]
"""
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
OUT = ROOT / 'src' / 'Empire Earth' / 'Database' / 'EEDataTextSpecs.h'
WORLD_OUT = ROOT / 'include' / 'ee' / 'EEWorldConstants.h'


def generate(spec):
    """EEDataTextSpecs.h: the record sizes, for EEDataTextFile.cpp's static_asserts against the structs the loaders
    read (the text compiler's own specs are Rust: rustgen.py)."""
    o = ['// GENERATED by tools/eedata/cppgen.py from tools/eedata/specs.json: do not edit (eedata.py cppgen).',
         '// The db record sizes the C++ pins: the text compiler itself is Rust (tools/eedata/rustgen.py).',
         '#ifndef EE_DATATEXTSPECS_H',
         '#define EE_DATATEXTSPECS_H',
         '',
         f'#define EEDT_FORMAT_VERSION {spec["format"]}',
         '',
         '// record sizes (EEDataTextFile.cpp static_asserts them against the structs the loaders read)',
         'enum EEDTRecordSize {']
    for sname, s in spec['structs'].items():
        o.append(f'    kEEDTSize_{sname} = {s["size"]},')
    o += ['};', '', '#endif']
    return ('\n'.join(o) + '\n').encode('ascii')


def camel(snake):
    return ''.join(w[:1].upper() + w[1:] for w in snake.split('_'))


VALUE_NAMES = {'mFloatValue': 'F', 'mFloatValue2': 'F2', 'mLongValue': 'L', 'mLongValue2': 'L2'}


def generate_world(spec):
    """include/ee/EEWorldConstants.h: dbworld's rows by their ids (the constants' names): the code reads a constant
    as gWorldTable.GetLongValue(kWorldUnitLimitRange), never by a raw row number."""
    names = spec['row_names']['dbworld']
    fields = spec['tables']['dbworld'].get('row_fields', {})
    o = ['// GENERATED by tools/eedata/cppgen.py from tools/eedata/specs.json (overlay.WORLD_ROWS): do not edit',
         '// (eedata.py cppgen). The dbworld constants by their ids: the row of each (its runtime key) and the values its',
         '// readers use (F mFloatValue, F2 mFloatValue2, L mLongValue, L2 mLongValue2; docs/DATA_FORMATS.md 8.3). The',
         '// EEWorldTable accessors take an EEWorldConstant, so a raw row number does not compile.',
         '#ifndef EE_EEWORLDCONSTANTS_H', '#define EE_EEWORLDCONSTANTS_H', '', 'enum EEWorldConstant {']
    for k, v in sorted(names.items(), key=lambda kv: int(kv[0])):
        used = ' '.join(VALUE_NAMES[f] for f in fields.get(k, []))
        o.append(f'    kWorld{camel(v)} = {int(k)},'.ljust(56) + f'// {v}: {used}')
    o.append('};')
    o.append('')
    o.append('// the research times of the unit improvements: one row per improvement kind, from improvement_time_area_effect')
    o.append('inline EEWorldConstant EEWorldImprovementTime(long inKind)')
    o.append('{')
    o.append('    return static_cast<EEWorldConstant>(kWorldImprovementTimeAreaEffect + inKind);')
    o.append('}')
    o.append('')
    o.append('#endif')
    return ('\n'.join(o) + '\n').encode('ascii')


def run(a, spec):
    status = 0
    for out, new in ((OUT, generate(spec)), (WORLD_OUT, generate_world(spec))):
        if a.check:
            ok = out.exists() and out.read_bytes() == new
            print(f'{out.name} is ' + ('up to date' if ok else 'STALE: run eedata.py cppgen'))
            status |= 0 if ok else 1
            continue
        out.write_bytes(new)
        print(f'-> {out}')
    return status
