"""Generate the C++ table specs (src/Empire Earth/Database/EEDataTextSpecs.h) from specs.json, so the game's text
loader and the Python converter read one layout description.

  python -I tools/eedata/eedata.py cppgen [--check]
"""
import pathlib
import sys

import binfmt
import scalars

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
OUT = ROOT / 'src' / 'Empire Earth' / 'Database' / 'EEDataTextSpecs.h'
TYPES = ['s8', 'u8', 'bool', 's16', 'u16', 's32', 'u32', 'f32', 'pair_f32', 'str']
CONTAINERS = ['count', 'lead', 'fixed', 'events', 'techtree', 'epochs']


def _c(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def _bytes(b, indent):
    """A byte string as C string literals, 32 bytes a line (the literal's own NUL is not part of it)."""
    return ('\n' + indent).join('"' + ''.join(f'\\x{x:02x}' for x in b[i:i + 32]) + '"' for i in range(0, len(b), 32))


def _record(b):
    """A record's bytes for the header: 0 when they are all zero."""
    return _bytes(b, '     ') if any(b) else '0'


def generate(spec):
    o = []
    o.append('// GENERATED by tools/eedata/cppgen.py from tools/eedata/specs.json: do not edit (eedata.py cppgen).')
    o.append('// The db table layouts for the text loader (EEDataText.cpp); the Python converter reads the same specs.')
    o.append('#ifndef EE_DATATEXTSPECS_H')
    o.append('#define EE_DATATEXTSPECS_H')
    o.append('')
    o.append(f'#define EEDT_FORMAT_VERSION {spec["format"]}')
    o.append('')
    o.append('enum EEDTType { ' + ', '.join(f'kEEDT_{t}' for t in TYPES) + ' };')
    o.append('enum EEDTContainer { ' + ', '.join(f'kEEDTC_{c}' for c in CONTAINERS) + ' };')
    o.append('')
    o.append('struct EEDTField { const char* mName; unsigned short mOffset; unsigned short mCount; unsigned char mType; };')
    o.append('struct EEDTStruct { const char* mName; unsigned long mSize; const EEDTField* mFields; unsigned long mFieldCount;')
    o.append('                   const char* mBase; };   // the record every row starts from (zero + defaults; 0: all zero)')
    o.append('struct EEDTRowName { long mRow; const char* mName; const char* mFields; };   // mFields: the fields its readers use')
    o.append('// a reference: the field (or "@list", the trailing list) holds a row of mTable, written as its id; mNone: values')
    o.append('// that stay integers although they are a key of the target')
    o.append('struct EEDTRef { const char* mField; const char* mTable; const long* mNone; unsigned long mNoneCount;')
    o.append('                 bool mNever; };   // mNever: "never" is the target\'s row count (no row: an epoch never reached)')
    o.append('struct EEDTDerived { const char* mField; long mA; long mB; };   // epochs.yaml: a * position + b where left out')
    o.append('struct EEDTTable {')
    o.append('    const char* mName;            // file stem (db\\<name>.dat)')
    o.append('    unsigned char mContainer;     // EEDTContainer')
    o.append('    bool mYaml;                   // text form: .yaml (else .csv)')
    o.append('    const EEDTStruct* mRecord;')
    o.append('    const char* const* mLead;     // lead string specs: "Name", "Name[n]", "A|B[n]" (interleaved pairs)')
    o.append('    unsigned long mLeadCount;')
    o.append('    const char* mListName;        // trailing list (events, techtree) or 0')
    o.append('    bool mListSigned;')
    o.append('    const EEDTRowName* mRowNames; // dbworld: the id each row must have (the name of its readers)')
    o.append('    unsigned long mRowNameCount;')
    o.append('    const char* mHole;            // the record of an unlisted row (an empty database row; 0: all zero)')
    o.append('    const char* mKeyField;        // the runtime integer of a row: this field (dbtechtree mID), or 0: its row position')
    o.append('    const char* mSelfField;       // the field that holds the row key + mSelfOffset (left out of the text), or 0')
    o.append('    long mSelfOffset;')
    o.append('    const EEDTRef* mRefs;         // the references to rows of other tables')
    o.append('    unsigned long mRefCount;')
    o.append('    const EEDTDerived* mDerived;  // fields that follow from the position (epochs)')
    o.append('    unsigned long mDerivedCount;')
    o.append('    bool mTextOnly;               // no db file of its own (epochs: compiles into dbtechtree)')
    o.append('};')
    o.append('')
    o.append('// record sizes (EEDataTextFile.cpp static_asserts them against the structs the loaders read)')
    o.append('enum EEDTRecordSize {')
    for sname, s in spec['structs'].items():
        o.append(f'    kEEDTSize_{sname} = {s["size"]},')
    o.append('};')
    o.append('')
    sidx = {}
    for sname, s in spec['structs'].items():
        sym = 'kEEDTFields_' + sname
        o.append(f'static const EEDTField {sym}[] = {{')
        for f in binfmt.exported(s['fields']):
            o.append(f'    {{{_c(f["name"])}, 0x{f["off"]:03x}, {f["count"]}, kEEDT_{f["type"]}}},')
        o.append('};')
        sidx[sname] = len(sidx)
    o.append('')
    o.append('static const EEDTStruct kEEDTStructs[] = {')
    for sname, s in spec['structs'].items():
        o.append(f'    {{{_c(sname)}, {s["size"]}, kEEDTFields_{sname}, '
                 f'sizeof(kEEDTFields_{sname}) / sizeof(EEDTField),')
        o.append('     ' + _record(binfmt.base_record(s)) + '},')
    o.append('};')
    o.append('')
    for name, t in spec['tables'].items():
        if t.get('lead'):
            o.append(f'static const char* const kEEDTLead_{name}[] = {{' + ', '.join(_c(x) for x in t['lead']) + '};')
        for fn, r in t.get('refs', {}).items():
            if r['none']:
                o.append(f'static const long kEEDTNone_{name}_{fn.lstrip("@")}[] = {{' +
                         ', '.join(str(v) for v in r['none']) + '};')
        if t.get('refs'):
            o.append(f'static const EEDTRef kEEDTRefs_{name}[] = {{')
            for fn, r in t['refs'].items():
                none = f'kEEDTNone_{name}_{fn.lstrip("@")}, {len(r["none"])}' if r['none'] else '0, 0'
                o.append(f'    {{{_c(fn)}, {_c(r["table"])}, {none}, {"true" if r.get("never") else "false"}}},')
            o.append('};')
        if t.get('derived'):
            o.append(f'static const EEDTDerived kEEDTDerived_{name}[] = {{' +
                     ', '.join(f'{{{_c(k)}, {a}, {b}}}' for k, (a, b) in t['derived'].items()) + '};')
        rn = spec.get('row_names', {}).get(name)
        if rn:
            o.append(f'static const EEDTRowName kEEDTRows_{name}[] = {{')
            rf = t.get('row_fields', {})
            for k, v in sorted(rn.items(), key=lambda kv: int(kv[0])):
                o.append(f'    {{{int(k)}, {_c(v)}, {_c(" ".join(rf.get(k, [])))}}},')
            o.append('};')
    o.append('')
    o.append('static const EEDTTable kEEDTTables[] = {')
    for name, t in spec['tables'].items():
        lead = f'kEEDTLead_{name}, {len(t["lead"])}' if t.get('lead') else '0, 0'
        lst = f'{_c(t["list"][0])}, {"true" if t["list"][1] == "s32" else "false"}' if t.get('list') else '0, false'
        rn = spec.get('row_names', {}).get(name)
        rows = f'kEEDTRows_{name}, {len(rn)}' if rn else '0, 0'
        o.append(f'    {{{_c(name)}, kEEDTC_{t["container"]}, {"true" if t["format"] == "yaml" else "false"}, '
                 f'&kEEDTStructs[{sidx[t["struct"]]}], {lead}, {lst}, {rows},')
        key = _c(t['key']) if t.get('key', 'row') not in ('row', 'position') else '0'
        der = f'kEEDTDerived_{name}, {len(t["derived"])}' if t.get('derived') else '0, 0'
        self_ = f'{_c(t["self"][0])}, {t["self"][1]}' if t.get('self') else '0, 0'
        refs = f'kEEDTRefs_{name}, {len(t["refs"])}' if t.get('refs') else '0, 0'
        o.append('     ' + _record(binfmt.hole_record(t, spec['structs'][t['struct']])) + ',')
        o.append(f'     {key}, {self_}, {refs}, {der}, {"true" if t.get("text_only") else "false"}}},')
    o.append('};')
    o.append('static const unsigned long kEEDTTableCount = sizeof(kEEDTTables) / sizeof(EEDTTable);')
    o.append('')
    o.append('// CP-1252 byte -> Unicode code point (the five undefined bytes map to the C1 code point of the same value)')
    o.append('static const unsigned short kEEDTCodePage[256] = {')
    cps = [ord(scalars.decode_str(bytes([b]))) for b in range(256)]
    for i in range(0, 256, 16):
        o.append('    ' + ', '.join(f'0x{c:04x}' for c in cps[i:i + 16]) + ',')
    o.append('};')
    o.append('')
    o.append('#endif')
    return ('\n'.join(o) + '\n').encode('ascii')


def run(a, spec):
    new = generate(spec)
    if a.check:
        ok = OUT.exists() and OUT.read_bytes() == new
        print(f'{OUT.name} is ' + ('up to date' if ok else 'STALE: run eedata.py cppgen'))
        return 0 if ok else 1
    OUT.write_bytes(new)
    print(f'-> {OUT}')
    return 0
