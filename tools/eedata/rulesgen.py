"""Generate both languages' rules code from tools/eedata/rules_schema.json (docs/RUST_PLAN.md R2.1): the rules documents'
enums, structs, defaults, the snapshot the C++ reads and the content dump. Output: include/ee/EERulesGen.h and
src/Empire Earth/Database/EERulesGenDecode.h (C++), rust/crates/ee_data/src/generated/rules_gen.rs (Rust).

  python -I tools/eedata/eedata.py rulesgen [--check]

The rules' document readers (the semantic checks) are hand written in Rust (ee_data/src/rules.rs), as rules.py's
validator is in Python; both read this schema's name tables.
"""
import json
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SCHEMA = HERE / 'rules_schema.json'
INC = ROOT / 'include' / 'ee'
CPP_TYPES = INC / 'EERulesGen.h'
CPP_DECODE = ROOT / 'src' / 'Empire Earth' / 'Database' / 'EERulesGenDecode.h'
RUST_OUT = ROOT / 'rust' / 'crates' / 'ee_data' / 'src' / 'generated' / 'rules_gen.rs'
HEADERS = [('EEUnitClassIDs.h', 'kUnitCategory'), ('EEUnitClassIDs.h', 'kUnitType'), ('EEStringIDs.h', 'IDS_'),
           ('EETechTreeTechID.h', 'kTech'), ('EECivPowerIDs.h', 'kCivPower')]


def load():
    return json.loads(SCHEMA.read_text(encoding='utf-8'))


def _symbols(schema):
    """{symbol: int}: the constants the schema's defaults name, from the C++ headers and the schema's enums."""
    out = {}
    for header, prefix in HEADERS:
        text = (INC / header).read_text(encoding='latin-1')
        out.update({n: int(v, 0) for n, v in re.findall(r'\b(' + prefix + r'\w*)\s*=\s*(0x[0-9a-fA-F]+|\d+)', text)})
        out.update({n: int(v, 0) for n, v in re.findall(r'#define\s+(' + prefix + r'\w*)\s+(0x[0-9a-fA-F]+|\d+)', text)})
    for e in schema['enums'].values():
        if 'cpp_prefix' in e:
            for i, v in enumerate(e['cpp_values']):
                out[e['cpp_prefix'] + v] = (1 << i) if e.get('bits') else i
    return out


class Gen:
    def __init__(self):
        self.s = load()
        self.sym = _symbols(self.s)
        self.structs = {x['name']: x for x in self.s['structs']}

    def value(self, v):
        """A default: an int, or 'SYM', 'SYM+n', 'SYM-SYM' (a constant expression over the headers' constants)."""
        if isinstance(v, (int, float)):
            return v
        total, sign = 0, 1
        for tok in re.findall(r'[+-]|[A-Za-z_0-9]+', v):
            if tok == '+':
                sign = 1
            elif tok == '-':
                sign = -1
            else:
                total += sign * (int(tok, 0) if tok[0].isdigit() else self.sym[tok])
                sign = 1
        return total

    def snake(self, cpp):
        name = cpp[1:] if cpp.startswith('m') and cpp[1:2].isupper() else cpp
        return '_'.join(p.lower() for p in re.findall(r'[A-Z]+(?=[A-Z][a-z])|[A-Z]?[a-z]+|[A-Z]+|\d+', name))


def _lit(x):
    """A float as a shortest literal (the same text for both languages' f32 parsers)."""
    r = repr(float(x))
    return r if 'e' in r or '.' in r else r + '.0'


# ------------------------------------------------------------------------------------------- C++


def cpp_type(f, gen):
    t = f['type']
    if t == 'int':
        return 'long', ''
    if t == 'float':
        return 'float', ''
    if t == 'bool':
        return 'bool', ''
    if t == 'number':
        return 'EERuleNumber', ''
    if t == 'string':
        return 'std::string', ''
    if t == 'int_list':
        return 'std::vector<long>', ''
    if t == 'float_list':
        return 'std::vector<float>', ''
    if t == 'float_array':
        return 'float', f'[{f["count"]}]'
    if t.startswith('list:'):
        return f'std::vector<{t[5:]}>', ''
    raise ValueError(t)


def cpp_default(f, gen):
    if f.get('nodefault_cpp') or 'default' not in f:
        return ''
    t, v = f['type'], f['default']
    if t == 'int':
        return f' = {gen.value(v["const"] if isinstance(v, dict) else v)}'
    if t == 'float':
        return f' = {_lit(v)}f'
    if t == 'bool':
        return ' = true' if v else ' = false'
    if t == 'string':
        return f' = "{v}"'
    if t == 'number':
        if 'world' in v:
            return f' = EERuleNumber::World({v["world"][0]}, {v["world"][1]})'
        return f' = EERuleNumber::Constant({_lit(v["const"])}f)'
    if t == 'float_array':
        return ' = {' + ', '.join(_lit(x) + 'f' for x in v) + '}'
    return ''   # lists: the snapshot fills them


def _doc(lines, indent):
    return [indent + '// ' + x for x in lines.split('\n')]


def generate_cpp(gen):
    o = ['// GENERATED by tools/eedata/rulesgen.py from tools/eedata/rules_schema.json: do not edit (eedata.py rulesgen).',
         '// The rules documents\' data: every value starts at its default and is filled from the Rust loader\'s snapshot',
         '// (EERules.cpp, ee_data rules_gen.rs). Portable C++17.',
         '#ifndef EE_EERULESGEN_H', '#define EE_EERULESGEN_H', '', '#include <string>', '#include <vector>', '']
    for name, e in gen.s['enums'].items():
        if 'doc' in e:
            o += _doc(e['doc'], '')
        if 'cpp_enum' in e:
            o.append(f'enum {e["cpp_enum"]} {{')
            for i, v in enumerate(e['cpp_values']):
                sym = e['cpp_prefix'] + v
                doc = e['value_docs'][i] if e.get('value_docs') else None
                val = f' = {1 << i}' if e.get('bits') else ''
                o.append(f'    {sym}{val},' + (f'   // {doc}' if doc else ''))
            if e.get('bits'):
                o.append(f'    {e["cpp_all"]} = {(1 << len(e["cpp_values"])) - 1},')
            if 'cpp_count' in e and not e.get('bits'):
                o.append(f'    {e["cpp_count"]},')
            o.append('};')
        if 'cpp_table' in e:
            o.append(f'extern const char* const {e["cpp_table"]}[];')
            o.append(f'extern const unsigned long {e["cpp_count"]};')
        o.append('')
    for st in gen.s['structs']:
        if 'section' in st:
            o.append(f'// {"-" * 88} {st["section"]}')
            o.append('')
        if 'doc' in st:
            o += _doc(st['doc'], '')
        o.append(f'struct {st["name"]} {{')
        for f in st['fields']:
            if 'doc' in f:
                o += _doc(f['doc'], '    ')
            ty, arr = cpp_type(f, gen)
            o.append(f'    {ty} {f["cpp"]}{arr}{cpp_default(f, gen)};')
        for m in st.get('methods', []):
            o.append(f'    {m}')
        o.append('};')
        o.append('')
    o.append('#endif')
    return ('\n'.join(o) + '\n').encode('utf-8')


def cpp_decode_field(f, indent, v):
    t = f['type']
    if t == 'int':
        return [f'{indent}{v} = Int(p);']
    if t == 'float':
        return [f'{indent}{v} = Float(p);']
    if t == 'bool':
        return [f'{indent}{v} = Bool(p);']
    if t == 'number':
        return [f'{indent}Number(p, {v});']
    if t == 'string':
        return [f'{indent}{v} = Str(p);']
    if t == 'int_list':
        return [f'{indent}{v}.resize(Count(p));', f'{indent}for (long& x : {v})', f'{indent}    x = Int(p);']
    if t == 'float_list':
        return [f'{indent}{v}.resize(Count(p));', f'{indent}for (float& x : {v})', f'{indent}    x = Float(p);']
    if t == 'float_array':
        return [f'{indent}for (int k = 0; k < {f["count"]}; k++)', f'{indent}    {v}[k] = Float(p);']
    if t.startswith('list:'):
        return [f'{indent}{v}.resize(Count(p));', f'{indent}for ({t[5:]}& e : {v})', f'{indent}    Decode(p, e);']
    if t.startswith('struct:'):
        return [f'{indent}Decode(p, {v});']
    raise ValueError(t)


def generate_decode(gen):
    o = ['// GENERATED by tools/eedata/rulesgen.py from tools/eedata/rules_schema.json: do not edit (eedata.py rulesgen).',
         '// Decodes the Rust rules snapshot (ee_data_rules_encode) into the structs of ee/EERulesGen.h. Included by',
         '// EERules.cpp.',
         'namespace EERulesGen {',
         'static long Int(const unsigned char*& p)',
         '{',
         '    long v = (long)(int)((unsigned)p[0] | (unsigned)p[1] << 8 | (unsigned)p[2] << 16 | (unsigned)p[3] << 24);',
         '    p += 4;',
         '    return v;',
         '}',
         'static float Float(const unsigned char*& p)',
         '{',
         '    unsigned u = (unsigned)p[0] | (unsigned)p[1] << 8 | (unsigned)p[2] << 16 | (unsigned)p[3] << 24;',
         '    p += 4;',
         '    float f;',
         '    memcpy(&f, &u, 4);',
         '    return f;',
         '}',
         'static bool Bool(const unsigned char*& p) { return *p++ != 0; }',
         'static unsigned long Count(const unsigned char*& p) { return (unsigned long)Int(p); }',
         'static std::string Str(const unsigned char*& p)',
         '{',
         '    unsigned long n = Count(p);',
         '    std::string s((const char*)p, n);',
         '    p += n;',
         '    return s;',
         '}',
         'static void Number(const unsigned char*& p, EERuleNumber& n)',
         '{',
         '    n.mFloat = Float(p);',
         '    n.mLong = Int(p);',
         '    n.mWorldRow = Int(p);',
         '    n.mWorldValue = (int)Int(p);',
         '}',
         '']
    for st in gen.s['structs']:
        o.append(f'static void Decode(const unsigned char*& p, {st["name"]}& r);')
    o.append('')
    for st in gen.s['structs']:
        o.append(f'static void Decode(const unsigned char*& p, {st["name"]}& r)')
        o.append('{')
        for f in st['fields']:
            o += cpp_decode_field(f, '    ', f'r.{f["cpp"]}')
        o.append('}')
    o.append('')
    o.append('static void DecodeAll(const unsigned char*& p, EERules& r)')
    o.append('{')
    for f in gen.s['top']:
        o += cpp_decode_field(f, '    ', f'r.{f["cpp"]}')
    o.append('}')
    o.append('}  // namespace EERulesGen')
    return ('\n'.join(o) + '\n').encode('utf-8')


# ------------------------------------------------------------------------------------------- Rust


def rust_type(f, gen):
    t = f['type']
    m = {'int': 'i32', 'float': 'f32', 'bool': 'bool', 'number': 'RuleNumber', 'string': 'Vec<u8>',
         'int_list': 'Vec<i32>', 'float_list': 'Vec<f32>'}
    if t in m:
        return m[t]
    if t == 'float_array':
        return f'[f32; {f["count"]}]'
    if t.startswith('list:'):
        return f'Vec<{gen.structs[t[5:]]["rust"]}>'
    raise ValueError(t)


def rust_value(v, ty, gen):
    """A value in Rust's terms: the schema's default or a list_defaults entry."""
    if ty == 'int':
        return str(gen.value(v["const"] if isinstance(v, dict) else v))
    if ty == 'float':
        return _lit(v) + '_f32'
    if ty == 'bool':
        return 'true' if v else 'false'
    if ty == 'string':
        return f'b"{v}".to_vec()'
    if ty == 'number':
        if 'world' in v:
            return f'RuleNumber::world({v["world"][0]}, {v["world"][1]})'
        return f'RuleNumber::constant({_lit(v["const"])}_f32)'
    if ty == 'int_list':
        return 'vec![' + ', '.join(str(gen.value(x)) for x in v) + ']'
    if ty == 'float_list':
        return 'vec![' + ', '.join(_lit(x) + '_f32' for x in v) + ']'
    if ty == 'float_array':
        return '[' + ', '.join(_lit(x) + '_f32' for x in v) + ']'
    if ty.startswith('list:'):
        st = gen.structs[ty[5:]]
        return 'vec![' + ', '.join(rust_literal(st, x, gen) for x in v) + ']'
    raise ValueError(ty)


def rust_literal(st, row, gen):
    """One struct value from a list_defaults entry: fields it names, the struct's default for the rest."""
    known = {f['cpp']: f for f in st['fields']}
    bad = set(row) - set(known)
    if bad:
        raise ValueError(f'{st["name"]}: {bad}')
    parts = []
    for cpp, v in row.items():
        f = known[cpp]
        parts.append(f'{gen.snake(cpp)}: {rust_value(v, f["type"], gen)}')
    return st['rust'] + ' { ' + ', '.join(parts) + ', ..Default::default() }'


def rust_default_expr(f, gen):
    if 'default_rust' in f:
        return f'default_{f["default_rust"]}()'
    t = f['type']
    if 'default' not in f:
        return 'Default::default()' if t != 'float_array' else '[0.0; 5]'
    return rust_value(f['default'], t, gen)


def rust_encode(f, gen, v):
    t = f['type']
    if t in ('int', 'bool', 'float', 'number', 'string'):
        return f'enc_{t}(out, {"&" if t in ("number", "string") else ""}{v});'
    if t == 'int_list':
        return f'enc_len(out, {v}.len()); for x in &{v} {{ enc_int(out, *x); }}'
    if t == 'float_list':
        return f'enc_len(out, {v}.len()); for x in &{v} {{ enc_float(out, *x); }}'
    if t == 'float_array':
        return f'for x in &{v} {{ enc_float(out, *x); }}'
    if t.startswith('list:'):
        return f'enc_len(out, {v}.len()); for x in &{v} {{ x.encode(out); }}'
    if t.startswith('struct:'):
        return f'{v}.encode(out);'
    raise ValueError(t)


def rust_dump(f, gen, v):
    t, k = f['type'], f['dump']
    if t == 'int':
        return f'j.int(b"{k}", {v});'
    if t == 'float':
        return f'j.float(b"{k}", {v});'
    if t == 'bool':
        return f'j.int(b"{k}", i32::from({v}));'
    if t == 'number':
        return f'j.number(b"{k}", &{v});'
    if t == 'string':
        return f'j.string(b"{k}", &{v});'
    if t == 'int_list':
        return f'j.list(b"{k}", &{v});'
    if t == 'float_array':
        return f'for (k, x) in {v}.iter().enumerate() {{ j.float(format!("{k}{{k}}").as_bytes(), *x); }}'
    if t.startswith('list:'):
        return (f'j.open(Some(b"{k}"), b\'[\'); for x in &{v} {{ j.open(None, b\'{{\'); x.dump(j); '
                f'j.close(b\'}}\'); }} j.close(b\']\');')
    raise ValueError(t)


def generate_rust(gen):
    o = ['// GENERATED by tools/eedata/rulesgen.py from tools/eedata/rules_schema.json: do not edit (eedata.py rulesgen).',
         '#![allow(clippy::all)]',
         '',
         'use crate::rules::{enc_bool, enc_float, enc_int, enc_len, enc_number, enc_string, Json, RuleNumber};',
         '']
    for name, e in gen.s['enums'].items():
        o.append(f'pub const {name.upper()}_NAMES: &[&str] = &[' + ', '.join(f'"{n}"' for n in e['names']) + '];')
        if 'cpp_prefix' in e:
            for i, v in enumerate(e['cpp_values']):
                sym = gen.snake(e['cpp_prefix'] + v).upper()
                o.append(f'pub const {sym}: i32 = {(1 << i) if e.get("bits") else i};')
            if 'cpp_count' in e and not e.get('bits'):
                o.append(f'pub const {gen.snake(e["cpp_count"]).upper()}: usize = {len(e["cpp_values"])};')
    for sym in gen.s['epoch_constants']:
        o.append(f'pub const {gen.snake(sym).upper()}: i32 = {gen.sym[sym]};')
    o.append('')
    for st in gen.s['structs']:
        o.append('#[derive(Clone, Debug, PartialEq)]')
        o.append(f'pub struct {st["rust"]} {{')
        for f in st['fields']:
            o.append(f'    pub {gen.snake(f["cpp"])}: {rust_type(f, gen)},')
        o.append('}')
        o.append(f'impl Default for {st["rust"]} {{')
        o.append('    fn default() -> Self {')
        o.append('        Self {')
        for f in st['fields']:
            o.append(f'            {gen.snake(f["cpp"])}: {rust_default_expr(f, gen)},')
        o.append('        }')
        o.append('    }')
        o.append('}')
        o.append(f'impl {st["rust"]} {{')
        o.append('    pub fn encode(&self, out: &mut Vec<u8>) {')
        for f in st['fields']:
            o.append('        ' + rust_encode(f, gen, 'self.' + gen.snake(f['cpp'])))
        o.append('    }')
        if st.get('dump', True):
            o.append('    pub fn dump(&self, j: &mut Json<\'_>) {')
            for f in st['fields']:
                if f.get('dump'):
                    o.append('        ' + rust_dump(f, gen, 'self.' + gen.snake(f['cpp'])))
            o.append('    }')
        o.append('}')
        o.append('')
    for n, sname in (('attributes', 'EECivAttribute'), ('powers', 'EECivPowerRule'), ('personalities', 'EEAIPersonalityRule')):
        st = gen.structs[sname]
        o.append(f'pub fn default_{n}() -> Vec<{st["rust"]}> {{')
        o.append('    vec![')
        for row in gen.s['list_defaults'][n]:
            o.append('        ' + rust_literal(st, row, gen) + ',')
        o.append('    ]')
        o.append('}')
    o.append('')
    o.append('pub const DOCUMENTS: &[&str] = &[' + ', '.join(f'"{n}"' for n in gen.s['documents']) + '];')
    o.append('')
    o.append('pub fn encode_top(r: &crate::rules::Rules, out: &mut Vec<u8>) {')
    for f in gen.s['top']:
        o.append('    ' + rust_encode(f, gen, 'r.' + gen.snake(f['cpp'])))
    o.append('}')
    return ('\n'.join(o) + '\n').encode('utf-8')


def outputs():
    gen = Gen()
    return [(CPP_TYPES, generate_cpp(gen)), (CPP_DECODE, generate_decode(gen)), (RUST_OUT, generate_rust(gen))]


def run(a):
    status = 0
    for path, data in outputs():
        if a.check:
            ok = path.exists() and path.read_bytes() == data
            print(f'{path.name} is ' + ('up to date' if ok else 'STALE: run eedata.py rulesgen'))
            status |= 0 if ok else 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
            print(f'-> {path}')
    return status
