"""Human-readable tables from the text tables (eedata.py doc): the YAML stays the source of truth.

  python -I tools/eedata/eedata.py doc epochs TEXTDIR [OUT.md]

epochs: one row per epoch of epochs.yaml, in order: its position (the runtime id), id, label, the title string id,
the costs and time of the advance into it, its prerequisites, button and hot key, the techs it needs (mRequiredSOL)
and the node slots of its block, plus the number of techs dbtechtree.yaml puts in it. Written to OUT.md (outside the
repository or under build/: the values are game data) or printed.
"""
import pathlib
import sys

from textio import parse_yaml

COLS = [('#', None), ('id', 'id'), ('label', 'label'), ('title', 'mTitleID'), ('food', 'mCost2'),
        ('wood', 'mCost3'), ('stone', 'mCost4'), ('gold', 'mCost5'), ('iron', 'mCost6'), ('time ms', 'mBuildTime'),
        ('prerequisites', 'mPrerequisite'), ('button', 'mButton'), ('hot key', 'mHotKey'), ('techs needed', 'mRequiredSOL'),
        ('slots', 'slots'), ('techs', None)]


def epochs(textdir):
    d = pathlib.Path(textdir)
    eps = parse_yaml((d / 'epochs.yaml').read_bytes().decode('utf-8')).get('records') or []
    techs = parse_yaml((d / 'dbtechtree.yaml').read_bytes().decode('utf-8')).get('records') or []
    count = {}
    for t in techs:
        count[str(t.get('epoch'))] = count.get(str(t.get('epoch')), 0) + 1
    out = ['| ' + ' | '.join(c for c, _ in COLS) + ' |', '|' + '---|' * len(COLS)]
    for k, e in enumerate(eps):
        cells = []
        for c, f in COLS:
            if c == '#':
                cells.append(str(k))
            elif c == 'techs':
                cells.append(str(count.get(str(e.get('id')), 0)))
            elif f == 'mPrerequisite':
                p = [str(e.get(f'mPrerequisite{i}', '0')) for i in range(1, 5)]
                cells.append(', '.join(x for x in p if x not in ('0', '')) or '-')
            else:
                cells.append(str(e.get(f, '')))
        out.append('| ' + ' | '.join(cells) + ' |')
    return (f'# Epochs ({len(eps)}, from epochs.yaml)\n\nGenerated by `eedata.py doc epochs`; epochs.yaml is the '
            'source of truth.\n\n' + '\n'.join(out) + '\n')


def run(a):
    text = {'epochs': epochs}[a.what](a.text)
    if a.out:
        pathlib.Path(a.out).write_bytes(text.encode('utf-8'))
        print(f'-> {a.out}')
    else:
        sys.stdout.write(text)
    return 0
