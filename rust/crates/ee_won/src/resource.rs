//! The lobby's resource table (WONLobbyResource.cpp): every lobby string, image and sound global, the section and
//! key of the lobby's resource files it is read from, in the order the original read them
//! (`LobbyResource_SafeGlueResources`, which looked each section up again as it came) and released them
//! (`LobbyResource_UnloadResources`, the same order: strings emptied, images and sounds released). The globals stay
//! C++ (the lobby's code uses them by name); the C++ pairs each row with its global by name and runs the loads.
//! `golden_resource.txt` holds the original's statements, read from the C++ before the port.

use std::ffi::{c_char, CStr};

/// A resource's kind (the `ResourceConfig::SafeGet*` that reads it).
#[repr(C)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum EeWonResKind {
    String = 0,
    Image = 1,
    Sound = 2,
}

/// One row: the section, the key, the kind, the global's name.
#[derive(Clone, Copy, Debug)]
pub struct Row {
    pub section: &'static CStr,
    pub key: &'static CStr,
    pub kind: EeWonResKind,
    pub name: &'static CStr,
}

const fn r(section: &'static CStr, key: &'static CStr, kind: EeWonResKind, name: &'static CStr) -> Row {
    Row { section, key, kind, name }
}

