/// The statements the table stands for, as the golden writes them: a section lookup where the section changes,
/// a read per row, then a release per row in the same order.
pub fn statements() -> Vec<String> {
    let mut out = Vec::new();
    let mut section: Option<&CStr> = None;
    for row in RESOURCES {
        if section != Some(row.section) {
            out.push(format!("config {}", row.section.to_str().unwrap_or("")));
            section = Some(row.section);
        }
        let kind = match row.kind {
            EeWonResKind::String => "String",
            EeWonResKind::Image => "Image",
            EeWonResKind::Sound => "Sound",
        };
        out.push(format!("get {kind} {} -> {}", row.key.to_str().unwrap_or(""), row.name.to_str().unwrap_or("")));
    }
    for row in RESOURCES {
        let verb = if row.kind == EeWonResKind::String { "erase" } else { "release" };
        out.push(format!("{verb} {}", row.name.to_str().unwrap_or("")));
    }
    out
}

// ---- the C ABI

/// A row for the C++: NUL-terminated texts; `new_section` when the section differs from the previous row's.
#[repr(C)]
#[derive(Clone, Copy, Debug)]
pub struct EeWonResource {
    pub section: *const c_char,
    pub key: *const c_char,
    pub name: *const c_char,
    pub kind: EeWonResKind,
    pub new_section: bool,
}

#[no_mangle]
pub extern "C" fn ee_won_resource_count() -> usize {
    RESOURCES.len()
}

/// Row `index` (below `ee_won_resource_count`) into `out`; false past the end.
///
/// # Safety
/// `out` is writable.
#[no_mangle]
pub unsafe extern "C" fn ee_won_resource_row(index: usize, out: *mut EeWonResource) -> bool {
    let Some(row) = RESOURCES.get(index) else {
        return false;
    };
    let new_section = index == 0 || RESOURCES[index - 1].section != row.section;
    // SAFETY: writable (the contract); the texts are 'static
    unsafe {
        *out = EeWonResource {
            section: row.section.as_ptr(),
            key: row.key.as_ptr(),
            name: row.name.as_ptr(),
            kind: row.kind,
            new_section,
        }
    };
    true
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_is_the_originals_statements() {
        let golden: Vec<&str> = include_str!("golden_resource.txt").lines().collect();
        let got = statements();
        assert_eq!(got.len(), golden.len());
        for (k, (g, w)) in got.iter().zip(&golden).enumerate() {
            assert_eq!(g, w, "statement {k}");
        }
    }

    #[test]
    fn rows() {
        assert_eq!(ee_won_resource_count(), 469);
        let names: std::collections::BTreeSet<&CStr> = RESOURCES.iter().map(|r| r.name).collect();
        assert_eq!(names.len(), RESOURCES.len(), "each global once");
        let mut out = EeWonResource {
            section: std::ptr::null(),
            key: std::ptr::null(),
            name: std::ptr::null(),
            kind: EeWonResKind::String,
            new_section: false,
        };
        assert!(unsafe { ee_won_resource_row(0, &mut out) });
        assert!(out.new_section);
        assert_eq!(unsafe { CStr::from_ptr(out.name) }, c"LobbyGlobal_Cancel_String");
        assert!(unsafe { ee_won_resource_row(1, &mut out) });
        assert!(!out.new_section);
        assert!(!unsafe { ee_won_resource_row(469, &mut out) });
    }
}
