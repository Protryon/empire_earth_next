"""Writes tests/won/won_leaf34_new.h: the new classes' declarations (include/ee/wonapi/WONLobbyGUI.h) and their hosts'
one-statement cases (WONGUI/BrowserComponent.cpp, ListAreaToolTip.cpp, StringLocalize.cpp, StringLocalizeCalls.cpp),
and the paints' hosts and methods (ImageButton.cpp, TextListItem.cpp, MenuBehavior.cpp: Graphics and ListArea the
world's PaintGraphics and PaintList) as they are in the tree, over won_leaf34_world.h, the hosts renamed so the
driver can put its mutations between them and the Rust.

usage: python -I tests/won/won_leaf34_gen.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
GUI = ROOT / "src" / "Empire Earth" / "WONAPI" / "WONGUI"


def between(text, start, end):
    a = text.index(start)
    return text[a:text.index(end, a) + len(end)]


def main():
    hdr = (ROOT / "include" / "ee" / "wonapi" / "WONLobbyGUI.h").read_text("utf-8")
    browser_cls = between(hdr, "class BrowserComponent : public Container {", "\n};")
    tip_cls = between(hdr, "class ListAreaToolTip : public Component {", "\n};")
    tip_cls = tip_cls.replace("ee_won_guicpp_tip_call", "MutTip")
    b = (GUI / "BrowserComponent.cpp").read_text("utf-8")
    b_host = between(b, 'extern "C" intptr_t ee_won_guicpp_browser_call', "\n}\n").replace(
        'extern "C" intptr_t ee_won_guicpp_browser_call', "static intptr_t HostBrowser")
    b_ctor = between(b, "BrowserComponent::BrowserComponent()", "\n").replace("ee_won_guicpp_browser_call", "MutBrowser")
    b_dtor = between(b, "BrowserComponent::~BrowserComponent()", "\n")
    t = (GUI / "ListAreaToolTip.cpp").read_text("utf-8")
    t_open = between(t, "static void OpenWith(", "\n")
    t_host = between(t, 'extern "C" intptr_t ee_won_guicpp_tip_call', "\n}\n").replace(
        'extern "C" intptr_t ee_won_guicpp_tip_call', "static intptr_t HostTip")
    s = (GUI / "StringLocalize.cpp").read_text("utf-8")
    s_body = between(s, "static void LocalizeUnits(", "\n}\n}\n")[:-2]
    s_body = s_body.replace("LocalizeUnits, LocalizeNew", "MutUnits, MutNew")
    c = (GUI / "StringLocalizeCalls.cpp").read_text("utf-8")
    s_body += between(c, "// Returns the format string with <s1> replaced", "\n}\n}\n")[:-2]
    ib = (GUI / "ImageButton.cpp").read_text("utf-8")
    tl = (GUI / "TextListItem.cpp").read_text("utf-8")
    mb = (GUI / "MenuBehavior.cpp").read_text("utf-8")
    paints = "\n".join([
        between(ib, 'extern "C" intptr_t ee_won_guicpp_imgbtn_call', "\n}\n").replace(
            'extern "C" intptr_t ee_won_guicpp_imgbtn_call', "static intptr_t HostImgBtn"),
        between(ib, "void ImageButton::GetDesiredSize", "\n}\n"),
        between(ib, "void ImageButton::Paint", "\n"),
        between(tl, 'extern "C" intptr_t ee_won_guicpp_textitem_call', "\n}\n").replace(
            'extern "C" intptr_t ee_won_guicpp_textitem_call', "static intptr_t HostTextItem"),
        between(tl, "void TextListItem::CalcDimensions", "\n"),
        between(tl, "void TextListItem::Paint", "\n}\n"),
        between(mb, "static intptr_t MenuItemCall(", "\n}\n").replace("MenuItemCall", "HostMenu").replace(
            "ee_won_guicpp_textitem_call(", "MutTextItem("),
        between(mb, "void MenuItem::CalcDimensions", "\n"),
        between(mb, "void MenuItem::Paint", "\n}\n"),
    ])
    paints = paints.replace("ee_won_guicpp_imgbtn_call", "MutImgBtn").replace(
        "ee_won_guicpp_textitem_call", "MutTextItem").replace("MenuItemCall", "MutMenu")
    bg = (GUI / "Background.cpp").read_text("utf-8")
    paints += "\n" + between(bg, 'extern "C" intptr_t ee_won_guicpp_background_call', "\n}\n").replace(
        'extern "C" intptr_t ee_won_guicpp_background_call', "static intptr_t HostBg")
    paints += "\n" + between(bg, "void Background::Paint", "\n}\n").replace("ee_won_guicpp_background_call", "MutBg")
    paints = re.sub(r"\bListArea\b", "PaintList", re.sub(r"\bGraphics\b", "PaintGraphics", paints))
    out = f'''// Generated by tests/won/won_leaf34_gen.py from the tree: the new BrowserComponent and ListAreaToolTip (their
// declarations in WONLobbyGUI.h) and their hosts' cases, the lobby's formatting functions over the Rust GetStr, and
// the measures and paints of ImageButton, TextListItem, MenuItem and Background with their hosts, as they are, over
// won_leaf34_world.h. Do not edit; rerun the script.
namespace LfNew {{
using namespace Lf;
typedef EeWonBrowserOp Bo;
typedef EeWonTipOp To;
typedef EeWonLeafOp Lo;
static intptr_t MutBrowser(void*, EeWonBrowserOp, intptr_t, intptr_t);
static intptr_t MutTip(void*, EeWonTipOp, intptr_t, intptr_t);
static void MutUnits(const void*, EeWonLocalizeText*);
static void* MutNew(const void*, size_t);
static intptr_t MutImgBtn(void*, EeWonLeafOp, intptr_t, intptr_t);
static intptr_t MutTextItem(void*, EeWonLeafOp, intptr_t, intptr_t);
static intptr_t MutMenu(void*, EeWonLeafOp, intptr_t, intptr_t);
static intptr_t MutBg(void*, EeWonLeafOp, intptr_t, intptr_t);
static GUIString gEmptyGUIString;
{browser_cls}
{tip_cls}
{b_host}
{b_ctor}{b_dtor}
{t_open}
{t_host}
{s_body}
#include "won_leaf34_paint_classes.h"
{paints}
}} // namespace LfNew
'''
    (ROOT / "tests" / "won" / "won_leaf34_new.h").write_text(out, "utf-8", newline="\n")


if __name__ == "__main__":
    main()
